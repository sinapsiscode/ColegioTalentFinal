// Custom hooks for common animation patterns
export const useStaggerAnimation = (delay = 0.1) => ({
  variants: {
    hidden: { opacity: 0, y: 20 },
    visible: (i) => ({
      opacity: 1,
      y: 0,
      transition: {
        delay: i * delay,
        duration: 0.3
      }
    })
  }
})

export const useCountUpAnimation = (from = 0, to = 100) => ({
  initial: { count: from },
  animate: { count: to },
  transition: { duration: 2, ease: "easeOut" }
})

export const useTypewriterAnimation = (text, speed = 0.05) => ({
  initial: { width: 0 },
  animate: { width: "auto" },
  transition: { duration: text.length * speed, ease: "linear" }
})